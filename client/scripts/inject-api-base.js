// scripts/inject-api-base.js — menulis api-config.js ke output build dengan __API_BASE__ dari env.
// Dipanggil setelah `ng build` (script "build:prod").
// Tidak menyentuh index.html (menghindari % placeholder yang crash dev server).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputDir = path.join(__dirname, '..', 'dist', 'client', 'browser');
const apiConfigPath = path.join(outputDir, 'api-config.js');

const apiBase = process.env.__API_BASE__ || ''; // Vercel env

fs.writeFileSync(apiConfigPath, `// generated by inject-api-base.js\nwindow.__API_BASE__ = ${JSON.stringify(apiBase)};\n`, 'utf8');

console.log(`[inject] __API_BASE__ = "${apiBase || '(kosong → pakai domain sama)'}"`);
